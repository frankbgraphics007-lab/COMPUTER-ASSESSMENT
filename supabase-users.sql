create table if not exists public.staff_users (
  email text primary key, name text, reg text,
  role  text not null default 'teacher' check (role in ('admin','teacher'))
);
create table if not exists public.roster (
  id bigint generated always as identity primary key,
  adm text, name text not null, cls text not null, year int not null, sex text,
  active boolean not null default true,       -- only active students may sit exams
  unique (name, cls)
);
alter table public.staff_users enable row level security;
alter table public.roster      enable row level security;

create or replace function public.is_staff() returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from staff_users where lower(email) = lower(coalesce(auth.jwt()->>'email','')));
$$;
create or replace function public.is_admin() returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from staff_users where role = 'admin' and lower(email) = lower(coalesce(auth.jwt()->>'email','')));
$$;
create or replace function public.my_role() returns text language sql stable security definer set search_path = public as $$
  select role from staff_users where lower(email) = lower(coalesce(auth.jwt()->>'email','')) limit 1;
$$;

-- Teachers see users; ONLY the main admin can change them.
drop policy if exists su_read  on public.staff_users;  create policy su_read  on public.staff_users for select to authenticated using (public.is_staff());
drop policy if exists su_admin on public.staff_users;  create policy su_admin on public.staff_users for all    to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists ro_read  on public.roster;       create policy ro_read  on public.roster      for select to authenticated using (public.is_staff());
drop policy if exists ro_admin on public.roster;       create policy ro_admin on public.roster      for all    to authenticated using (public.is_admin()) with check (public.is_admin());

-- From now on only people listed in staff_users count as staff (any other signed-in account is locked out).
do $$ declare t text; begin
  foreach t in array array['assessments','exam_keys','class_pw','settings','results','live'] loop
    execute format('drop policy if exists staff_all on public.%I', t);
    execute format('create policy staff_all on public.%I for all to authenticated using (public.is_staff()) with check (public.is_staff())', t);
  end loop;
end $$;

-- Student side: look up / check a name on the roster (active students only)
create or replace function public.find_students(p_q text, p_year int) returns jsonb language sql security definer set search_path = public as $$
  select coalesce(jsonb_agg(x), '[]'::jsonb) from (
    select name, cls from roster
    where active and year = p_year and length(trim(coalesce(p_q,''))) >= 3
      and name ilike '%' || replace(replace(trim(p_q),'%',''),'_','') || '%'
    order by name limit 8) x;
$$;
create or replace function public.check_student(p_name text, p_year int) returns jsonb language plpgsql security definer set search_path = public as $$
declare r roster;
begin
  select * into r from roster where active and year = p_year
    and upper(name) = upper(regexp_replace(trim(coalesce(p_name,'')), '\s+', ' ', 'g')) limit 1;
  if not found then return jsonb_build_object('ok', false); end if;
  return jsonb_build_object('ok', true, 'name', r.name, 'cls', r.cls);
end $$;
revoke all on function public.my_role() from public, anon;
grant execute on function public.my_role() to authenticated;
grant execute on function public.find_students(text,int), public.check_student(text,int) to anon, authenticated;
grant execute on function public.is_staff(), public.is_admin() to authenticated;

